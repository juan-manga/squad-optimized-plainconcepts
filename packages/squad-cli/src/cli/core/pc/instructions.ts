/**
 * Project instructions generator (Squad Optimized — Plain Concepts).
 *
 * Generates the instruction files every host reads, from one detected stack:
 *  - AGENTS.md                         (hub: OpenCode, Codex, Copilot, Claude via pointer)
 *  - .github/copilot-instructions.md   (Copilot: repo-wide)
 *  - .github/instructions/*.instructions.md (Copilot: path-scoped, applyTo)
 *  - CLAUDE.md                         (Claude Code: imports AGENTS.md)
 *
 * Content lives in a managed block (`<!-- squad-pc:start -->…<!-- squad-pc:end -->`)
 * so re-running is idempotent and anything the team wrote outside it is kept.
 * The hub stays short and links to rules instead of restating them (Plain
 * Concepts Platform convention), which keeps every agent's base context small.
 */

import fs from 'node:fs';
import path from 'node:path';
import { detectStack, type ProjectStack } from './stack.js';

export const BLOCK_START = '<!-- squad-pc:start -->';
export const BLOCK_END = '<!-- squad-pc:end -->';

export interface InstructionsOptions {
  hosts: string[];
  openspec: boolean;
  repomap: boolean;
  rtk: boolean;
  graphify: boolean;
}

/** Insert or replace the managed block in a file. Returns true when content changed. */
export function upsertManagedBlock(file: string, block: string, opts: { title?: string } = {}): boolean {
  const wrapped = `${BLOCK_START}\n${block.trim()}\n${BLOCK_END}`;
  let current = '';
  try { current = fs.readFileSync(file, 'utf8'); } catch { /* new file */ }
  let next: string;
  const s = current.indexOf(BLOCK_START);
  const e = current.indexOf(BLOCK_END);
  if (s !== -1 && e > s) next = current.slice(0, s) + wrapped + current.slice(e + BLOCK_END.length);
  else if (current.trim()) next = `${current.trimEnd()}\n\n${wrapped}\n`;
  else next = `${opts.title ? `# ${opts.title}\n\n` : ''}${wrapped}\n`;
  if (next === current) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, next);
  return true;
}

function commandsSection(stack: ProjectStack): string {
  const c = stack.commands;
  const rows = ([['Install', c.install], ['Build', c.build], ['Test', c.test], ['Lint', c.lint], ['Dev', c.dev]] as const)
    .filter(([, v]) => v)
    .map(([k, v]) => `- **${k}:** \`${v}\``);
  return rows.length ? rows.join('\n') : '- _No build/test commands detected — the Lead should fill these in._';
}

function contextRules(o: InstructionsOptions): string[] {
  const rules = [
    'Keep changes small and focused; prefer editing over rewriting files.',
    'Run the test command before declaring work done; never weaken or skip tests to go green.',
    'Reuse before you build: search for an existing helper/component first and say what you reused.',
  ];
  if (o.repomap) rules.unshift('Start from `.squad/context/repomap.md` to locate code before searching; read only the files you need.');
  if (o.graphify) rules.push('For "how does X relate to Y" questions use `graphify query` / `graphify-out/GRAPH_REPORT.md` instead of broad greps.');
  if (o.rtk) rules.push('Shell output is compacted by RTK (`rtk gain` shows savings); use `rtk bypass <cmd>` only when you need raw output.');
  if (o.openspec) rules.push('Non-trivial changes start as an OpenSpec change (`openspec/changes/<name>/`: proposal, design, tasks, spec deltas). App-code PRs must touch a spec, change or decision record.');
  return rules;
}

export function buildAgentsHub(stack: ProjectStack, o: InstructionsOptions): string {
  const links = [
    '- Team, roles and routing: `.squad/team.md`, `.squad/routing.md`',
    '- Decisions (read before starting): `.squad/decisions.md`',
    o.repomap ? '- Codebase map: `.squad/context/repomap.md`' : '',
    o.openspec ? '- Specs and change proposals: `openspec/specs/`, `openspec/changes/`' : '',
    '- AI maturity (AIDLC) assessment and roadmap: `.squad/aidlc/assessment.md`',
    fs.existsSync(path.join(stack.root, 'ARCHITECTURE.md')) ? '- Architecture: `ARCHITECTURE.md`' : '',
    fs.existsSync(path.join(stack.root, 'docs', 'decisions')) ? '- ADRs: `docs/decisions/`' : '',
  ].filter(Boolean);
  return [
    '## Project overview (generated by Squad Optimized — Plain Concepts)',
    '',
    `- **Languages:** ${stack.languages.slice(0, 5).join(', ') || 'unknown'}`,
    `- **Frameworks:** ${stack.frameworks.join(', ') || '—'}`,
    stack.topDirs.length ? `- **Code lives in:** ${stack.topDirs.slice(0, 12).map((d) => `\`${d}/\``).join(', ')}` : '',
    '',
    '## Commands',
    '',
    commandsSection(stack),
    '',
    '## Where to look',
    '',
    ...links,
    '',
    '## Working rules',
    '',
    ...contextRules(o).map((r) => `- ${r}`),
    '',
    '_This block is regenerated by `squad optimize instructions`. Write project-specific rules outside it._',
  ].filter((l) => l !== undefined).join('\n').replace(/\n{3,}/g, '\n\n');
}

function scopedInstructions(stack: ProjectStack): Array<{ name: string; applyTo: string; body: string }> {
  const out: Array<{ name: string; applyTo: string; body: string }> = [];
  const langs = new Set(stack.languages);
  const fw = new Set(stack.frameworks);
  if (langs.has('TypeScript') || langs.has('JavaScript')) {
    out.push({
      name: 'typescript', applyTo: '**/*.{ts,tsx,js,jsx,mts,cts}',
      body: [
        '- Strict TypeScript: no `any` without a comment explaining why; prefer `unknown` + narrowing.',
        '- Keep modules small and side-effect free at import time.',
        fw.has('React') ? '- React: function components + hooks; colocate component, test and styles; no business logic in components.' : '',
        fw.has('Plain Concepts Platform') ? '- Use `@plainconceptsplatform/ui-components` and design tokens before writing new UI; follow Feature-Sliced Design layers.' : '',
      ].filter(Boolean).join('\n'),
    });
  }
  if (langs.has('C#')) {
    out.push({
      name: 'dotnet', applyTo: '**/*.{cs,csproj,razor}',
      body: [
        '- Nullable reference types on; treat warnings as errors in new projects.',
        '- Async all the way (`Async` suffix, pass `CancellationToken`).',
        '- Prefer integration tests over mocks for API behaviour (testing trophy).',
      ].join('\n'),
    });
  }
  if (langs.has('Python')) {
    out.push({
      name: 'python', applyTo: '**/*.py',
      body: '- Type hints on public functions; `ruff` clean; tests with `pytest` (run via `uv run pytest` when uv is used).',
    });
  }
  if (stack.hasTests) {
    out.push({
      name: 'tests', applyTo: '**/{test,tests,__tests__,spec}/**,**/*.{test,spec}.*,**/*Tests.cs',
      body: [
        '- Test behaviour, not implementation. Every test asserts something meaningful.',
        '- No skipped/focused tests, no snapshot-only or mock-only tests, no assertion-less tests.',
        '- Test code should not outgrow the code under test.',
      ].join('\n'),
    });
  }
  return out;
}

export interface InstructionsResult { written: string[] }

export function generateInstructions(root: string, o: InstructionsOptions): InstructionsResult {
  const stack = detectStack(root);
  const hub = buildAgentsHub(stack, o);
  const written: string[] = [];
  const rel = (p: string) => path.relative(root, p).replace(/\\/g, '/');

  const agentsMd = path.join(root, 'AGENTS.md');
  if (upsertManagedBlock(agentsMd, hub, { title: 'AGENTS.md' })) written.push(rel(agentsMd));

  if (o.hosts.includes('copilot')) {
    const ci = path.join(root, '.github', 'copilot-instructions.md');
    const block = `${hub}\n\nFull agent rules: see \`AGENTS.md\`. Path-specific rules: \`.github/instructions/\`.`;
    if (upsertManagedBlock(ci, block, { title: 'Copilot instructions' })) written.push(rel(ci));
    for (const s of scopedInstructions(stack)) {
      const f = path.join(root, '.github', 'instructions', `${s.name}.instructions.md`);
      const content = `---\napplyTo: "${s.applyTo}"\n---\n\n${BLOCK_START}\n${s.body}\n${BLOCK_END}\n`;
      if (fs.existsSync(f)) {
        const existing = fs.readFileSync(f, 'utf8');
        if (!existing.includes(BLOCK_START) || existing === content) continue; // user-owned or unchanged
      }
      fs.mkdirSync(path.dirname(f), { recursive: true });
      fs.writeFileSync(f, content);
      written.push(rel(f));
    }
  }

  if (o.hosts.includes('claude')) {
    const claudeMd = path.join(root, 'CLAUDE.md');
    if (upsertManagedBlock(claudeMd, '@AGENTS.md\n\nProject rules live in `AGENTS.md` (imported above) so every AI host shares one source of truth.', { title: 'CLAUDE.md' })) {
      written.push(rel(claudeMd));
    }
  }
  return { written };
}
